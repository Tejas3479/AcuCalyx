@dataclass
class PlanningPipelineResult:
    """Consolidated outputs and artifacts generated by the planning pipeline."""
    case_id: str
    provenance: CaseProvenanceRecord
    quality_gate: QualityGateResult
    pcs_visibility: PCSVisibilityResult
    stones: List[StoneMorphometry]
    attenuations: List[StoneAttenuationProfile]
    candidates: List[CandidateTrajectory]
    monte_carlo_assessments: Dict[str, List[MonteCarloRiskAssessment]]
    fluoroscopy_views: Dict[str, Dict[str, ProjectedTrajectoryView]]
    mesh_exports: Dict[str, MeshExportResult]
    report_pdf_path: Optional[Path]
    output_dir: Path
    status: str  # 'SUCCESS', 'GATE_REJECTED', 'PARTIAL'


def segment_heuristic_anatomy(
    volume_hu: np.ndarray,
    spatial_orientation: SpatialOrientation,
    target_side: str = "left",
    known_kidney_center: Optional[np.ndarray] = None
) -> AnatomicalCorridorMasks:
    """
    Synthesizes anatomical corridor masks from CT intensity and spatial priors
    when pre-trained neural segmentation weights are not mounted.
    
    Includes:
    - Target kidney parenchyma (10 to 75 HU)
    - Skeletal ribs & spine (>250 HU)
    - Colon with air lumen / soft-tissue wall
    - Thoracic lower lung & derived pleural reflection envelope
    - Intercostal neurovascular bundle risk corridor
    """
    masks = AnatomicalCorridorMasks(spatial_orientation=spatial_orientation)
    rows, cols, slices = volume_hu.shape
    dx, dy, dz = spatial_orientation.spacing
    origin = spatial_orientation.origin

    # Coordinate grids in physical space
    i_idx, j_idx, k_idx = np.indices((rows, cols, slices))
    # Transform grid sample points
    # Affine: X_phys, Y_phys, Z_phys
    A = spatial_orientation.affine_matrix
    X_phys = A[0, 0]*i_idx + A[0, 1]*j_idx + A[0, 2]*k_idx + A[0, 3]
    Y_phys = A[1, 0]*i_idx + A[1, 1]*j_idx + A[1, 2]*k_idx + A[1, 3]
    Z_phys = A[2, 0]*i_idx + A[2, 1]*j_idx + A[2, 2]*k_idx + A[2, 3]

    # 1. Ribs & Bone (> 250 HU)
    bone_mask = volume_hu > 250.0
    # Ribs are lateral (|X| > 15 mm) and dorsal / lateral
    rib_mask = bone_mask & (np.abs(X_phys) > 15.0)
    spine_mask = bone_mask & (np.abs(X_phys) <= 15.0)

    # Subdivide ribs into 11th and 12th based on craniocaudal level (Z)
    if np.any(rib_mask):
        rib_z = Z_phys[rib_mask]
        z_mid = (np.min(rib_z) + np.max(rib_z)) / 2.0
        rib_12 = rib_mask & (Z_phys <= z_mid)
        rib_11 = rib_mask & (Z_phys > z_mid)
    else:
        rib_12 = np.zeros_like(volume_hu, dtype=bool)
        rib_11 = np.zeros_like(volume_hu, dtype=bool)

    if target_side.lower() == "left":
        masks.set_mask(OrganLabel.RIB_LEFT_12, rib_12 & (X_phys > 0))
        masks.set_mask(OrganLabel.RIB_LEFT_11, rib_11 & (X_phys > 0))
    else:
        masks.set_mask(OrganLabel.RIB_RIGHT_12, rib_12 & (X_phys < 0))
        masks.set_mask(OrganLabel.RIB_RIGHT_11, rib_11 & (X_phys < 0))

    masks.set_mask(OrganLabel.VERTEBRAE_SPINE, spine_mask)

    # 2. Kidney Parenchyma
    # Typical HU: 20 to 65 HU, located on target side (Left: X > 5, Right: X < -5)
    side_filter = (X_phys > 5.0) if target_side.lower() == "left" else (X_phys < -5.0)
    # Kidney is retroperitoneal (dorsal half, Y > -20.0 typically)
    kidney_hu_candidate = (volume_hu >= 15.0) & (volume_hu <= 75.0) & side_filter

    if known_kidney_center is not None:
        # Distance to known center < 55 mm
        dist_to_center = np.sqrt(
            (X_phys - known_kidney_center[0])**2 +
            (Y_phys - known_kidney_center[1])**2 +
            (Z_phys - known_kidney_center[2])**2
        )
        kidney_mask = kidney_hu_candidate & (dist_to_center <= 55.0)
    else:
        # Largest connected component in retroperitoneal side quadrant
        labeled, num_features = ndimage.label(kidney_hu_candidate)
        if num_features > 0:
            sizes = ndimage.sum(kidney_hu_candidate, labeled, range(1, num_features + 1))
            largest_idx = np.argmax(sizes) + 1
            kidney_mask = labeled == largest_idx
        else:
            kidney_mask = np.zeros_like(volume_hu, dtype=bool)

    # Smooth kidney mask
    if np.any(kidney_mask):
        struct = ndimage.generate_binary_structure(3, 1)
        kidney_mask = ndimage.binary_opening(kidney_mask, structure=struct)
        kidney_mask = ndimage.binary_closing(kidney_mask, structure=struct)

    if target_side.lower() == "left":
        masks.set_mask(OrganLabel.KIDNEY_LEFT, kidney_mask)
    else:
        masks.set_mask(OrganLabel.KIDNEY_RIGHT, kidney_mask)

    # 3. Colon Hazard (Retrorenal / lateral colon: air lumen -1000 to -500 HU, soft tissue wall)
    colon_air = (volume_hu < -400.0) & side_filter & (Y_phys > -30.0)
    # Exclude cranial lung slices
    if np.any(kidney_mask):
        k_max_z = np.max(Z_phys[kidney_mask])
        colon_air = colon_air & (Z_phys <= (k_max_z + 10.0))

    if np.any(colon_air):
        struct = ndimage.generate_binary_structure(3, 1)
        # Dilate air lumen by 3-4mm to include colon muscularis wall
        dilate_voxels = max(1, int(round(3.5 / np.mean([dx, dy, dz]))))
        colon_mask = ndimage.binary_dilation(colon_air, structure=struct, iterations=dilate_voxels)
    else:
        colon_mask = np.zeros_like(volume_hu, dtype=bool)

    masks.set_mask(OrganLabel.COLON, colon_mask)

    # 4. Lung Lower Lobe & Pleural Reflection Envelope
    # Air in upper posterior thorax (Z > kidney center Z, HU < -450)
    if np.any(kidney_mask):
        k_mid_z = (np.min(Z_phys[kidney_mask]) + np.max(Z_phys[kidney_mask])) / 2.0
        lung_raw = (volume_hu < -450.0) & (Z_phys > k_mid_z) & side_filter
        # Keep connected components
        lung_mask = lung_raw
    else:
        lung_mask = np.zeros_like(volume_hu, dtype=bool)

    if target_side.lower() == "left":
        masks.set_mask(OrganLabel.LUNG_LEFT, lung_mask)
        pleura = derive_pleural_reflection_envelope(lung_mask, spatial_orientation, inferior_expansion_mm=18.0)
        masks.set_mask(OrganLabel.PLEURAL_ENVELOPE_LEFT, pleura)
    else:
        masks.set_mask(OrganLabel.LUNG_RIGHT, lung_mask)
        pleura = derive_pleural_reflection_envelope(lung_mask, spatial_orientation, inferior_expansion_mm=18.0)
        masks.set_mask(OrganLabel.PLEURAL_ENVELOPE_RIGHT, pleura)

    # 5. Intercostal Neurovascular Bundle Risk Zone (inferior margin of 11th and 12th ribs)
    combined_ribs = masks.get_combined_ribs_mask(side=target_side)
    nv_bundle = derive_intercostal_neurovascular_risk_zone(combined_ribs, spatial_orientation, inferior_buffer_mm=4.0)
    if target_side.lower() == "left":
        masks.set_mask(OrganLabel.INTERCOSTAL_NV_BUNDLE_LEFT, nv_bundle)
    else:
        masks.set_mask(OrganLabel.INTERCOSTAL_NV_BUNDLE_RIGHT, nv_bundle)

    return masks


def create_needle_cylinder_mesh(
    trajectory: LineSegment3D,
    radius_mm: float = 0.9,
    color_rgba: Tuple[float, float, float, float] = (0.2, 0.8, 0.2, 1.0)
) -> trimesh.Trimesh:
    """
    Creates a 3D cylindrical mesh representing the needle shaft in physical space.
    """
    start = trajectory.start_point
    end = trajectory.end_point
    vec = end - start
    length = float(np.linalg.norm(vec))
    if length < 1e-4:
        length = 1.0

    # Create base cylinder oriented along Z axis
    cyl = trimesh.creation.cylinder(radius=radius_mm, height=length, sections=16)

    # Translation to center
    mid_point = (start + end) / 2.0
    cyl_dir = np.array([0.0, 0.0, 1.0])
    target_dir = vec / length

    # Rotation matrix aligning [0, 0, 1] to target_dir
    axis = np.cross(cyl_dir, target_dir)
    axis_norm = np.linalg.norm(axis)
    if axis_norm < 1e-6:
        if np.dot(cyl_dir, target_dir) < 0:
            rot_mat = trimesh.transformations.rotation_matrix(np.pi, [1, 0, 0])
        else:
            rot_mat = np.eye(4)
    else:
        axis = axis / axis_norm
        angle = np.arccos(np.clip(np.dot(cyl_dir, target_dir), -1.0, 1.0))
        rot_mat = trimesh.transformations.rotation_matrix(angle, axis)

    rot_mat[0:3, 3] = mid_point
    cyl.apply_transform(rot_mat)

    # Color
    color_255 = [int(round(c * 255)) for c in color_rgba]
    cyl.visual.vertex_colors = np.full((len(cyl.vertices), 4), color_255, dtype=np.uint8)
    return cyl


def run_planning_pipeline(
    input_path: Union[str, Path],
    output_dir: Union[str, Path],
    side: str = "left",
    case_id: Optional[str] = None,
    config: Optional[Dict[str, Any]] = None
) -> PlanningPipelineResult:
    """
    Executes the comprehensive AcuCalyx planning pipeline.
    
    Args:
        input_path: Path to DICOM directory or NIfTI file (.nii, .nii.gz)
        output_dir: Path to directory where output artifacts and JSONs will be stored
        side: Target kidney side ('left' or 'right')
        case_id: Optional explicit case identifier string
        config: Optional configuration overrides (e.g. coarse_step_mm, monte_carlo_samples)
    """
    cfg = config or {}
    out_path = Path(output_dir)
    out_path.mkdir(parents=True, exist_ok=True)
    meshes_dir = out_path / "meshes"
    meshes_dir.mkdir(parents=True, exist_ok=True)

    input_p = Path(input_path)
    case_id = case_id or f"CASE_{input_p.stem.upper()}"

    # -------------------------------------------------------------
    # Step 1: Ingestion & Quality Gate
    # -------------------------------------------------------------
    logger.info(f"Ingesting imaging data from: {input_p}")
    if input_p.is_dir():
        # Clinical DICOM series
        dicom_res = load_dicom_series(input_p)
        volume_hu = dicom_res.volume_hu
        spatial = dicom_res.spatial_orientation
        quality_gate = dicom_res.quality_gate
        input_hash = dicom_res.metadata.series_sha256
        study_uid = dicom_res.metadata.study_instance_uid
        series_uid = dicom_res.metadata.series_instance_uid
    else:
        # Research NIfTI
        nifti_res = load_research_nifti(input_p)
        volume_hu = nifti_res.volume_hu
        spatial = nifti_res.spatial_orientation
        input_hash = compute_sha256_file(input_p)
        study_uid = f"NIFTI_STUDY_{input_p.stem}"
        series_uid = f"NIFTI_SERIES_{input_p.stem}"
        from acucalyx.ingestion.quality_gate import QualityGateResult
        quality_gate = QualityGateResult(
            passed=True,
            rejection_reasons=[],
            warnings=[],
            geometry_score=1.0,
            resolution_score=1.0,
            overall_quality_tier='HIGH',
            slice_thickness_mm=float(spatial.spacing[2]),
            pixel_spacing_mm=(float(spatial.spacing[0]), float(spatial.spacing[1])),
            slice_spacing_mm=float(spatial.spacing[2]),
            is_contrast_enhanced=None,
            reconstruction_kernel="Standard/NIfTI"
        )

    # Cryptographic Provenance record
    provenance = create_provenance_record(
        case_id=case_id,
        study_uid=study_uid,
        series_uid=series_uid,
        input_data_hash=input_hash,
        config_dict=cfg,
        software_version="2.1.0"
    )

    # Fail-closed check
    if not quality_gate.passed and not cfg.get("allow_marginal", False):
        logger.error(f"Image quality gate failed for {case_id}: {quality_gate.rejection_reasons}")
        # Save quality.json and provenance.json
        with open(out_path / "quality.json", "w") as f:
            json.dump(asdict(quality_gate), f, indent=2)
        with open(out_path / "provenance.json", "w") as f:
            json.dump(asdict(provenance), f, indent=2)
        return PlanningPipelineResult(
            case_id=case_id,
            provenance=provenance,
            quality_gate=quality_gate,
            pcs_visibility=PCSVisibilityResult(
                state=PCSVisibilityState.NOT_ASSESSABLE,
                confidence_score=0.0,
                fluid_cavity_volume_mm3=0.0,
                mean_internal_hu=0.0,
                allows_direct_puncture_lock=False,
                clinical_notice="DICOM Quality Gate Rejected."
            ),
            stones=[],
            attenuations=[],
            candidates=[],
            monte_carlo_assessments={},
            fluoroscopy_views={},
            mesh_exports={},
            report_pdf_path=None,
            output_dir=out_path,
            status="GATE_REJECTED"
        )

    # -------------------------------------------------------------
    # Step 2: Anatomical Segmentation & Thoracic Envelopes
    # -------------------------------------------------------------
    logger.info("Executing anatomical corridor segmentation...")
    anatomy_masks = segment_heuristic_anatomy(
        volume_hu=volume_hu,
        spatial_orientation=spatial,
        target_side=side
    )
    kidney_mask = anatomy_masks.get_kidney_mask(side=side)
    colon_mask = anatomy_masks.get_mask(OrganLabel.COLON)
    pleura_mask = anatomy_masks.get_mask(
        OrganLabel.PLEURAL_ENVELOPE_LEFT if side == "left" else OrganLabel.PLEURAL_ENVELOPE_RIGHT
    )
    ribs_mask = anatomy_masks.get_combined_ribs_mask(side=side)
    nv_mask = anatomy_masks.get_mask(
        OrganLabel.INTERCOSTAL_NV_BUNDLE_LEFT if side == "left" else OrganLabel.INTERCOSTAL_NV_BUNDLE_RIGHT
    )

    # -------------------------------------------------------------
    # Step 3: Stone Detection, Volumetry, & Attenuation
    # -------------------------------------------------------------
    logger.info("Detecting stone candidates and characterizing attenuation...")
    raw_stones = detect_stone_candidates(
        ct_volume_hu=volume_hu,
        spatial_orientation=spatial,
        kidney_mask=kidney_mask,
        min_volume_voxels=cfg.get("min_stone_voxels", 4)
    )
    if not raw_stones:
        # Fallback to whole volume search excluding bone ribs
        raw_stones = detect_stone_candidates(
            ct_volume_hu=volume_hu,
            spatial_orientation=spatial,
            kidney_mask=None,
            min_volume_voxels=cfg.get("min_stone_voxels", 4)
        )
    stone_morphs: List[StoneMorphometry] = [
        compute_stone_morphometry(s, spatial) for s in raw_stones
    ]
    stone_attens: List[StoneAttenuationProfile] = [
        compute_stone_attenuation(s, volume_hu) for s in raw_stones
    ]

    # -------------------------------------------------------------
    # Step 4: Collecting System Visibility Gate
    # -------------------------------------------------------------
    logger.info("Evaluating pelvicalyceal system visibility...")
    is_contrast = bool(cfg.get("is_contrast_enhanced", False))
    pcs_result = classify_collecting_system_visibility(
        ct_volume_hu=volume_hu,
        kidney_mask=kidney_mask,
        spatial_orientation=spatial,
        is_contrast_enhanced=is_contrast
    )

    # -------------------------------------------------------------
    # Step 5: Flank Surface & Entry Sampling
    # -------------------------------------------------------------
    logger.info("Extracting skin surface and hierarchical flank entry points...")
    skin_mask = extract_body_surface_mask(volume_hu, threshold_hu=-300.0)
    flank_points = sample_hierarchical_flank_points(
        skin_surface_mask=skin_mask,
        spatial_orientation=spatial,
        anatomy_masks=anatomy_masks,
        side=side,
        coarse_step_mm=cfg.get("coarse_step_mm", 15.0)
    )

    # -------------------------------------------------------------
    # Step 6: Target Calyx Conical Puncture Zones
    # -------------------------------------------------------------
    logger.info("Synthesizing conical puncture target zones...")
    if np.any(kidney_mask):
        k_indices = np.argwhere(kidney_mask)
        phys_k = spatial.voxel_to_physical(k_indices)
        k_center = np.mean(phys_k, axis=0)
        k_radii = (np.max(phys_k, axis=0) - np.min(phys_k, axis=0)) / 2.0
    else:
        k_center = np.array([30.0 if side == "left" else -30.0, 10.0, 40.0])
        k_radii = np.array([25.0, 20.0, 45.0])

    stone_centroids = [s.centroid_lps_mm for s in stone_morphs]
    puncture_zones = generate_candidate_puncture_zones(
        kidney_center_lps=k_center,
        kidney_radii_lps=k_radii,
        pcs_visibility=pcs_result.state,
        detected_stone_centroids=stone_centroids,
        side=side
    )

    # -------------------------------------------------------------
    # Step 7: Distance Fields & Multi-Objective Trajectory Optimization
    # -------------------------------------------------------------
    logger.info("Computing anisotropic distance fields and evaluating trajectories...")
    df_colon = DistanceField(colon_mask, spatial) if (colon_mask is not None and np.any(colon_mask)) else None
    df_pleura = DistanceField(pleura_mask, spatial) if (pleura_mask is not None and np.any(pleura_mask)) else None
    df_ribs = DistanceField(ribs_mask, spatial) if (ribs_mask is not None and np.any(ribs_mask)) else None

    candidates: List[CandidateTrajectory] = []
    cand_counter = 1

    for skin_pt in flank_points:
        for zone in puncture_zones:
            traj = LineSegment3D(
                start_point=skin_pt.physical_lps_mm,
                end_point=zone.apex_papilla_lps_mm
            )
            # Evaluate coaxial infundibular entry
            is_coax, angle_dev = zone.is_trajectory_coaxial(traj.unit_direction)

            # Evaluate clearances
            hazard_evals: List[HazardClearanceResult] = []
            if df_colon is not None:
                h_col = df_colon.evaluate_trajectory_clearance(
                    trajectory=traj,
                    hazard_name="colon",
                    uncertainty_geometry=1.0,
                    uncertainty_segmentation=1.5,
                    uncertainty_position=2.5
                )
                hazard_evals.append(h_col)
            if df_pleura is not None:
                h_pl = df_pleura.evaluate_trajectory_clearance(
                    trajectory=traj,
                    hazard_name="pleural_recess",
                    uncertainty_geometry=1.0,
                    uncertainty_segmentation=2.0,
                    uncertainty_position=3.0
                )
                hazard_evals.append(h_pl)
            if df_ribs is not None:
                h_rib = df_ribs.evaluate_trajectory_clearance(
                    trajectory=traj,
                    hazard_name="rib_bone",
                    uncertainty_geometry=0.5,
                    uncertainty_segmentation=0.5,
                    uncertainty_position=1.0
                )
                hazard_evals.append(h_rib)

            # Minimum effective clearance
            if hazard_evals:
                min_eff = min(h.effective_clearance_mm for h in hazard_evals)
            else:
                min_eff = 50.0

            # Stone reachability
            reach_info = evaluate_access_stone_reach(
                trajectory=traj,
                puncture_zone=zone,
                instrument=STANDARD_RIGID_NEPHROSCOPE,
                stones=stone_morphs
            )

            # Determine confidence tier
            if pcs_result.state in (PCSVisibilityState.DIRECTLY_OPACIFIED, PCSVisibilityState.HYDRONEPHROTIC_DISTENDED):
                conf_tier = "HIGH" if min_eff > 10.0 else "MODERATE"
            else:
                conf_tier = "MODERATE" if min_eff > 10.0 else "LOW"

            cand = CandidateTrajectory(
                candidate_id=f"CAND_{cand_counter:03d}",
                target_calyx_name=zone.calyx_group.value,
                entry_point_lps=skin_pt.physical_lps_mm,
                target_point_lps=zone.apex_papilla_lps_mm,
                tract_length_mm=float(traj.length),
                min_effective_clearance_mm=float(min_eff),
                hazard_evaluations=hazard_evals,
                reachable_stone_fraction=float(reach_info.reachable_stone_fraction),
                required_scope_deflection_deg=float(reach_info.max_required_deflection_deg),
                access_rib_classification=skin_pt.rib_approach_classification,
                is_pareto_optimal=False,
                confidence_tier=conf_tier
            )
            candidates.append(cand)
            cand_counter += 1

    # Extract Pareto frontier
    logger.info(f"Extracting Pareto frontier across {len(candidates)} candidates...")
    pareto_candidates = extract_pareto_frontier(candidates) if candidates else []

    # Sort candidates: non-colliding first, subcostal preferred, shorter tract length
    def candidate_sort_key(c: CandidateTrajectory):
        has_collision = any(h.is_intersecting for h in c.hazard_evaluations)
        rib_penalty = 0 if c.access_rib_classification == "SUBCOSTAL" else (1 if "11_12" in c.access_rib_classification else 2)
        return (has_collision, -c.is_pareto_optimal, rib_penalty, -c.min_effective_clearance_mm, c.tract_length_mm)

    ranked_candidates = sorted(pareto_candidates, key=candidate_sort_key)
    top_candidates = ranked_candidates[:5] if ranked_candidates else []

    # -------------------------------------------------------------
    # Step 8: Empirical Monte Carlo Uncertainty Simulation
    # -------------------------------------------------------------
    logger.info("Running Monte Carlo stochastic perturbation tests...")
    monte_carlo_assessments: Dict[str, List[MonteCarloRiskAssessment]] = {}
    mc_iterations = cfg.get("monte_carlo_samples", 200)

    for cand in top_candidates:
        cand_assessments: List[MonteCarloRiskAssessment] = []
        cand_seg = LineSegment3D(cand.entry_point_lps, cand.target_point_lps)
        if df_colon is not None:
            mc_col = run_monte_carlo_clearance_analysis(
                trajectory=cand_seg,
                distance_field=df_colon,
                hazard_name="colon",
                num_iterations=mc_iterations,
                random_seed=42
            )
            cand_assessments.append(mc_col)
        if df_pleura is not None:
            mc_pl = run_monte_carlo_clearance_analysis(
                trajectory=cand_seg,
                distance_field=df_pleura,
                hazard_name="pleural_recess",
                num_iterations=mc_iterations,
                random_seed=42
            )
            cand_assessments.append(mc_pl)
        monte_carlo_assessments[cand.candidate_id] = cand_assessments

    # -------------------------------------------------------------
    # Step 9: Virtual Fluoroscopy Projection Simulation
    # -------------------------------------------------------------
    logger.info("Simulating virtual fluoroscopy C-arm projections...")
    fluoroscopy_views: Dict[str, Dict[str, ProjectedTrajectoryView]] = {}
    for cand in top_candidates:
        cand_seg = LineSegment3D(cand.entry_point_lps, cand.target_point_lps)
        view_bullseye = simulate_trajectory_projection(cand_seg, view_type="BULLS_EYE")
        view_progression = simulate_trajectory_projection(cand_seg, view_type="PROGRESSION")

        fluoroscopy_views[cand.candidate_id] = {
            "BULLS_EYE": view_bullseye,
            "PROGRESSION": view_progression
        }

    # -------------------------------------------------------------
    # Step 10: 3D Surface Meshes & Trajectory Cylinders Export
    # -------------------------------------------------------------
    logger.info("Generating 3D surface meshes (GLB & STL)...")
    mesh_exports: Dict[str, MeshExportResult] = {}

    # Kidney mesh
    if np.any(kidney_mask):
        k_mesh = mask_to_surface_mesh(kidney_mask, spatial, target_faces=15000)
        res_k = export_mesh_glb(k_mesh, meshes_dir / "kidney.glb", organ_name="kidney")
        export_mesh_stl(k_mesh, meshes_dir / "kidney.stl", organ_name="kidney")
        mesh_exports["kidney"] = res_k

    # Stones mesh
    if raw_stones:
        combined_stones = np.zeros_like(volume_hu, dtype=bool)
        for s in raw_stones:
            combined_stones |= s.voxel_mask
        s_mesh = mask_to_surface_mesh(combined_stones, spatial, target_faces=5000)
        res_s = export_mesh_glb(s_mesh, meshes_dir / "stones.glb", organ_name="stones")
        export_mesh_stl(s_mesh, meshes_dir / "stones.stl", organ_name="stones")
        mesh_exports["stones"] = res_s

    # Colon mesh
    if colon_mask is not None and np.any(colon_mask):
        c_mesh = mask_to_surface_mesh(colon_mask, spatial, target_faces=12000)
        res_c = export_mesh_glb(c_mesh, meshes_dir / "colon.glb", organ_name="colon")
        mesh_exports["colon"] = res_c

    # Ribs mesh
    if ribs_mask is not None and np.any(ribs_mask):
        r_mesh = mask_to_surface_mesh(ribs_mask, spatial, target_faces=15000)
        res_r = export_mesh_glb(r_mesh, meshes_dir / "ribs.glb", organ_name="ribs")
        mesh_exports["ribs"] = res_r

    # Candidate needles as GLB
    for i, cand in enumerate(top_candidates[:3]):
        traj_seg = LineSegment3D(cand.entry_point_lps, cand.target_point_lps)
        # Preferred is green, others gold/orange
        needle_color = (0.1, 0.85, 0.2, 1.0) if i == 0 else (0.9, 0.7, 0.1, 1.0)
        needle_mesh = create_needle_cylinder_mesh(traj_seg, radius_mm=0.9, color_rgba=needle_color)
        res_n = export_mesh_glb(needle_mesh, meshes_dir / f"needle_{cand.candidate_id}.glb", organ_name="needle")
        mesh_exports[f"needle_{cand.candidate_id}"] = res_n

    # -------------------------------------------------------------
    # Step 11: Preoperative Planning PDF Report
    # -------------------------------------------------------------
    logger.info("Rendering Preoperative Planning Report PDF...")
    pdf_path = out_path / "report.pdf"
    generate_preoperative_planning_pdf(
        output_path=pdf_path,
        provenance=provenance,
        quality_gate=quality_gate,
        pcs_visibility=pcs_result,
        stones=stone_morphs,
        attenuations=stone_attens,
        candidates=top_candidates
    )

    # -------------------------------------------------------------
    # Step 12: Save Machine-Readable JSON Manifests
    # -------------------------------------------------------------
    logger.info("Saving JSON data packages...")
    with open(out_path / "quality.json", "w") as f:
        json.dump(asdict(quality_gate), f, indent=2)

    with open(out_path / "provenance.json", "w") as f:
        json.dump(asdict(provenance), f, indent=2)

    # Convert stones to serializable list
    stones_data = []
    for m, a in zip(stone_morphs, stone_attens):
        stones_data.append({
            "stone_id": m.stone_id,
            "volume_mm3": round(m.volume_mm3, 1),
            "max_feret_diameter_mm": round(m.max_feret_diameter_mm, 2),
            "centroid_lps_mm": [round(float(c), 2) for c in m.centroid_lps_mm],
            "bounding_box_span_mm": [round(float(s), 2) for s in m.bounding_box_span_mm],
            "tier": m.tier,
            "mean_hu": round(a.mean_hu, 1),
            "peak_hu": round(a.peak_hu, 1),
            "fraction_high_over_1000hu": round(a.fraction_high_over_1000hu, 3),
            "composition_inference": a.composition_inference
        })
    with open(out_path / "stones.json", "w") as f:
        json.dump(stones_data, f, indent=2)

    # Convert candidates to serializable list
    cands_data = []
    for c in top_candidates:
        hazards = []
        for h in c.hazard_evaluations:
            hazards.append({
                "hazard_name": h.hazard_name,
                "observed_clearance_mm": round(h.observed_clearance_mm, 2),
                "effective_clearance_mm": round(h.effective_clearance_mm, 2),
                "is_intersecting": h.is_intersecting,
                "confidence_level": h.confidence_level
            })
        cands_data.append({
            "candidate_id": c.candidate_id,
            "target_calyx": c.target_calyx_name,
            "entry_point_lps": [round(float(x), 2) for x in c.entry_point_lps],
            "target_point_lps": [round(float(x), 2) for x in c.target_point_lps],
            "tract_length_mm": round(c.tract_length_mm, 1),
            "min_effective_clearance_mm": round(c.min_effective_clearance_mm, 1),
            "reachable_stone_fraction": round(c.reachable_stone_fraction, 3),
            "required_scope_deflection_deg": round(c.required_scope_deflection_deg, 1),
            "access_rib_classification": c.access_rib_classification,
            "confidence_tier": c.confidence_tier,
            "is_pareto_optimal": c.is_pareto_optimal,
            "hazards": hazards
        })
    with open(out_path / "candidates.json", "w") as f:
        json.dump(cands_data, f, indent=2)

    # Uncertainty JSON
    unc_data = {}
    for cand_id, assessments in monte_carlo_assessments.items():
        unc_data[cand_id] = [
            {
                "hazard_name": a.hazard_name,
                "collision_probability": round(a.collision_probability, 4),
                "nominal_clearance_mm": round(a.nominal_clearance_mm, 2),
                "percentile_5th_clearance_mm": round(a.percentile_5th_clearance_mm, 2),
                "mean_perturbed_clearance_mm": round(a.mean_perturbed_clearance_mm, 2),
                "risk_category": a.risk_category
            }
            for a in assessments
        ]
    with open(out_path / "uncertainty.json", "w") as f:
        json.dump(unc_data, f, indent=2)

    logger.info(f"Pipeline successfully completed for case {case_id} -> {out_path}")
    return PlanningPipelineResult(
        case_id=case_id,
        provenance=provenance,
        quality_gate=quality_gate,
        pcs_visibility=pcs_result,
        stones=stone_morphs,
        attenuations=stone_attens,
        candidates=top_candidates,
        monte_carlo_assessments=monte_carlo_assessments,
        fluoroscopy_views=fluoroscopy_views,
        mesh_exports=mesh_exports,
        report_pdf_path=pdf_path,
        output_dir=out_path,
        status="SUCCESS"
    )
